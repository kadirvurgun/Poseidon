param([Parameter(Mandatory)][string]$Directory)
$ErrorActionPreference = 'Stop'
# Pure in-memory cryptography: no certificate-store writes or global trust changes.
$caKey = [Security.Cryptography.RSA]::Create(3072)
$caRequest = [Security.Cryptography.X509Certificates.CertificateRequest]::new('CN=POSEIDON synthetic lab CA', $caKey, [Security.Cryptography.HashAlgorithmName]::SHA256, [Security.Cryptography.RSASignaturePadding]::Pkcs1)
$caRequest.CertificateExtensions.Add([Security.Cryptography.X509Certificates.X509BasicConstraintsExtension]::new($true, $false, 0, $true))
$caRequest.CertificateExtensions.Add([Security.Cryptography.X509Certificates.X509KeyUsageExtension]::new('KeyCertSign, CrlSign', $true))
$caRequest.CertificateExtensions.Add([Security.Cryptography.X509Certificates.X509SubjectKeyIdentifierExtension]::new($caRequest.PublicKey, $false))
$now = [DateTimeOffset]::UtcNow
$ca = $caRequest.CreateSelfSigned($now.AddMinutes(-5), $now.AddDays(30))
$key = [Security.Cryptography.RSA]::Create(3072)
$request = [Security.Cryptography.X509Certificates.CertificateRequest]::new('CN=localhost', $key, [Security.Cryptography.HashAlgorithmName]::SHA256, [Security.Cryptography.RSASignaturePadding]::Pkcs1)
$san = [Security.Cryptography.X509Certificates.SubjectAlternativeNameBuilder]::new()
$san.AddDnsName('localhost')
$request.CertificateExtensions.Add($san.Build())
$request.CertificateExtensions.Add([Security.Cryptography.X509Certificates.X509BasicConstraintsExtension]::new($false, $false, 0, $true))
$request.CertificateExtensions.Add([Security.Cryptography.X509Certificates.X509KeyUsageExtension]::new('DigitalSignature, KeyEncipherment', $true))
$request.CertificateExtensions.Add([Security.Cryptography.X509Certificates.X509SubjectKeyIdentifierExtension]::new($request.PublicKey, $false))
$request.CertificateExtensions.Add([Security.Cryptography.X509Certificates.X509AuthorityKeyIdentifierExtension]::CreateFromCertificate($ca, $true, $false))
$usage = [Security.Cryptography.OidCollection]::new()
[void]$usage.Add([Security.Cryptography.Oid]::new('1.3.6.1.5.5.7.3.1'))
$request.CertificateExtensions.Add([Security.Cryptography.X509Certificates.X509EnhancedKeyUsageExtension]::new($usage, $true))
$serial = [Security.Cryptography.RandomNumberGenerator]::GetBytes(16)
$leaf = $request.Create($ca, $now.AddMinutes(-5), $now.AddDays(29), $serial)
[IO.File]::WriteAllText((Join-Path $Directory 'ca.pem'), $ca.ExportCertificatePem())
[IO.File]::WriteAllText((Join-Path $Directory 'tls.pem'), $leaf.ExportCertificatePem())
[IO.File]::WriteAllText((Join-Path $Directory 'tls.key'), $key.ExportPkcs8PrivateKeyPem())
$ca.Dispose(); $caKey.Dispose(); $leaf.Dispose(); $key.Dispose()
